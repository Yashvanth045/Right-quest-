def seed_if_empty(db, QuizQuestion):
    """Populate a fresh development database once so /quiz never starts empty."""
    if QuizQuestion.query.count() > 0:
        return 0
    inserted = 0
    for item in QUESTIONS:
        db.session.add(QuizQuestion(
            category=item["category"], country=item["country"],
            question=item["question"], options=item["options"],
            correct_answer=item["correct_answer"], explanation=item["explanation"],
            difficulty=item.get("difficulty", "medium"), source=item.get("source"),
            reviewed=True,
        ))
        inserted += 1
    db.session.commit()
    return inserted
